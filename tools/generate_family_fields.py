#!/usr/bin/env python3
"""Generate canonical scalar walkers for Jukebox/P2 (requires pycparser).
Unions have explicit semantic visitors; unknown field types fail generation.
The checked-in output makes pycparser unnecessary for normal builds.
"""
from pathlib import Path
import re,subprocess
from pycparser import c_parser,c_ast,c_generator
ROOT=Path(__file__).resolve().parents[1]
for module in ('ja','p2'):
    text='typedef unsigned long size_t;typedef unsigned char uint8_t;typedef signed char int8_t;typedef unsigned short uint16_t;typedef short int16_t;typedef unsigned int uint32_t;typedef int int32_t;typedef _Bool bool;\n'
    for name in ('resource.h','game.h'):
        text+=re.sub(r'^#include.*$','',(ROOT/module/name).read_text(),flags=re.M)+'\n'
    text=subprocess.run(['gcc','-E','-P','-x','c','-'],input=text,text=True,capture_output=True,check=True).stdout
    tree=c_parser.CParser().parse(text);structs={}
    class Collect(c_ast.NodeVisitor):
        def visit_Struct(self,node):
            if node.name and node.decls:structs[node.name]=node
            self.generic_visit(node)
    Collect().visit(tree)
    lines=['/* Generated by tools/generate_family_fields.py; explicit little-endian fields. */']
    counter=[0];gen=c_generator.CGenerator()
    def emit(node,expr,indent='  ',index='0'):
        if isinstance(node,c_ast.TypeDecl):return emit(node.type,expr,indent,index)
        if isinstance(node,c_ast.IdentifierType):
            t=' '.join(node.names);width={'uint8_t':1,'int8_t':1,'bool':1,'uint16_t':2,'int16_t':2,'uint32_t':4,'int32_t':4,'int':4}[t]
            lines.append(f'{indent}{"FS_BOOL" if t=="bool" else "FS_FIELD"}({expr}{"" if t=="bool" else ","+str(width)});');return
        if isinstance(node,c_ast.PtrDecl):lines.append(f'{indent}FS_REF({expr});');return
        if isinstance(node,c_ast.ArrayDecl):
            n='i'+str(counter[0]);counter[0]+=1
            lines.append(f'{indent}for(int {n}=0;{n}<({gen.visit(node.dim)});++{n}){{');emit(node.type,expr+'['+n+']',indent+'  ',n);lines.append(indent+'}');return
        if isinstance(node,c_ast.Struct):
            if node.name=='object_t':
                object_index='-1' if '.players_table[' in expr else index
                lines.append(f'{indent}family_object_codec(c,&({expr}),{object_index});');return
            node=structs[node.name] if node.name and node.decls is None else node
            for d in node.decls:
                if not d.name and isinstance(d.type,c_ast.Union):
                    if node.name=='level_monster_t':
                        lines.append(f'{indent}switch({expr}.type){{')
                        for u in d.type.decls:
                            lines.append(f'{indent}case {u.name[4:]}:');emit(u.type,expr+'.'+u.name,indent+'  ');lines.append(indent+'  break;')
                        lines.append(indent+'default:break;\n'+indent+'}');continue
                    if node.name=='level_platform_t':
                        lines.append(f'{indent}if(({expr}.flags&15)==8){{');emit(d.type.decls[0].type,expr+'.type8',indent+'  ');lines.append(indent+'}else{');emit(d.type.decls[1].type,expr+'.other',indent+'  ');lines.append(indent+'}');continue
                    raise ValueError(node.name)
                emit(d.type,expr+'.'+d.name,indent,index)
            return
        raise TypeError(type(node))
    lines.append('static void family_vars_codec(struct fs_codec *c,struct vars_t *v){');emit(structs['vars_t'],'(*v)');lines.append('}')
    if module=='p2':lines.append('static void family_level_codec(struct fs_codec *c,struct level_t *v){');emit(structs['level_t'],'(*v)');lines.append('}')
    (ROOT/module/'state_fields.h').write_text('\n'.join(lines)+'\n')

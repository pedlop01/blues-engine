#!/usr/bin/env python3
"""Replay bounded actor routines from private snapshots of the pinned audit.

Research only: no OS, game loop, audio or hardware blitter is executed. Snapshots
are generated by validate_fox_amiga_resources.py, never distributed.
"""
import argparse,json,subprocess
from pathlib import Path
from unicorn import Uc,UC_ARCH_M68K,UC_MODE_BIG_ENDIAN,UC_HOOK_CODE
from unicorn.m68k_const import UC_CPU_M68K_M68000,UC_M68K_REG_A7,UC_M68K_REG_D0,UC_M68K_REG_PC

def main():
    p=argparse.ArgumentParser(description=__doc__)
    for key in ('reference','probe','datapath','output'):p.add_argument('--'+key,type=Path,required=True)
    p.add_argument('--mode',choices=['platform','enemy'],default='platform');p.add_argument('--ticks',type=int,default=600)
    args=p.parse_args();out=args.output.resolve();root=args.datapath.resolve()
    if out.exists() or out==root or root in out.parents:raise ValueError('Use new private output outside originals')
    assert json.loads((args.reference/'report.json').read_text())['main_sha256']=='18ca46dd02a3ad3623b03d425f0e0ae489b5090498882aea6d2578161010bc45'
    out.mkdir(parents=True);results=[]
    for level in list(range(1,15))+[16]:
        cpu=Uc(UC_ARCH_M68K,UC_MODE_BIG_ENDIAN);cpu.ctl_set_cpu_model(UC_CPU_M68K_M68000);cpu.mem_map(0x10000,0x300000)
        state=(args.reference/f'enemy-state-{level}.bin').read_bytes();assert len(state)==0x300000;cpu.mem_write(0x10000,state)
        def word(address):return int.from_bytes(cpu.mem_read(address,2),'big')
        def signed(v):return v-65536 if v>=32768 else v
        def put(address,value):cpu.mem_write(address,(value&65535).to_bytes(2,'big'))
        def hook(u,address,size,user):
            if address==0x10002:u.emu_stop();return
            if address==0xe6160:
                sp=u.reg_read(UC_M68K_REG_A7);u.reg_write(UC_M68K_REG_D0,128);u.reg_write(UC_M68K_REG_PC,int.from_bytes(u.mem_read(sp,4),'big'));u.reg_write(UC_M68K_REG_A7,sp+4);return
            if 0xebfd4<=address<0xec156 or 0xe612c<=address<0xe6160 or (args.mode=='enemy' and (0xee1dc<=address<0xef300 or 0xe65d4<=address<0xe661c)):return
            raise ValueError(f'Platform routine escaped to {address:x}')
        cpu.hook_add(UC_HOOK_CODE,hook)
        process=subprocess.run([str(args.probe.resolve()),'--datapath',str(root),'--output',str(out/f'level-{level}'),'--level',str(level),'--'+args.mode+'-ticks',str(args.ticks)],capture_output=True,text=True,timeout=60)
        if process.returncode:raise ValueError(process.stderr)
        if args.mode=='enemy':
            frames=json.loads((out/f'level-{level}/enemy-motion.json').read_text());count=word(0x804a8)
            initial=[(signed(word(0x182000+i*92+2)),signed(word(0x182000+i*92+4))) for i in range(count)]
            for tick,rows in enumerate(frames):
                px,py=initial[(tick//120)%count] if count else (word(0x804fa),word(0x804fc));px+=-24 if tick%120<60 else 48;py+=0 if tick%80<40 else 64
                for address,value in {0x80526:tick,0x804f6:px,0x804f8:py,0x80564:max(0,px-160),0x80566:max(0,py-86),0x8049a:100}.items():put(address,value)
                cpu.reg_write(UC_M68K_REG_A7,0x2f0000-4);cpu.mem_write(0x2f0000-4,(0x10002).to_bytes(4,'big'));cpu.emu_start(0xef13e,0,count=500000)
                if cpu.reg_read(UC_M68K_REG_PC)!=0x10002:raise ValueError('Enemy instruction limit')
                for i,row in enumerate(rows):
                    for j,value in enumerate(row):
                        original=word(0x182000+i*92+j*2)
                        if value!=original:raise ValueError(f'Enemy level {level} tick {tick} actor {i} behavior {row[12]} offset {j*2}: native {value}, original {original}')
            results.append(dict(level=level,ticks=len(frames),reference_match=True));print(f'Enemies level {level}: {len(frames)} ticks match',flush=True);continue
        frames=json.loads((out/f'level-{level}/platform-motion.json').read_text());count=word(0x804aa)
        # Original data contains four malformed sprite ids. Disable these in
        # the reference too; the native runtime rejects out-of-bank rendering.
        rejected=0
        for i in range(count):
            if word(0x185200+i*40)>71:put(0x185200+i*40,0);rejected+=1
        for tick,frame in enumerate(frames):
            target=0x185200+((tick//120)%count)*40 if count else 0x804f8-2
            px,py=signed(word(target+2)),signed(word(target+4))
            if not count:px=word(0x804fa);py=word(0x804fc)
            for address,value in {0x804f6:px+8,0x804f8:py+1,0x80520:16,0x80564:max(0,px-160),0x80566:max(0,py-86),0x8050e:0,0x80510:0,0x8051a:0}.items():put(address,value)
            cpu.reg_write(UC_M68K_REG_A7,0x2f0000-4);cpu.mem_write(0x2f0000-4,(0x10002).to_bytes(4,'big'));cpu.emu_start(0xebfd4,0,count=500000)
            if cpu.reg_read(UC_M68K_REG_PC)!=0x10002:raise ValueError('Platform instruction limit')
            for i,row in enumerate(frame['platforms']):
                for j,value in enumerate(row):
                    original=word(0x185200+i*40+j*2)
                    if value!=original:raise ValueError(f'Level {level} tick {tick} platform {i} offset {j*2}: native {value}, original {original}')
            actual=[signed(word(a)) for a in (0x804f6,0x804f8,0x80520,0x8050e)]
            if actual!=frame['player']:raise ValueError(f'Level {level} tick {tick} player: native {frame["player"]}, original {actual}')
        results.append(dict(level=level,ticks=len(frames),rejected_sprites=rejected,reference_match=True));print(f'Platforms level {level}: {len(frames)} ticks match',flush=True)
    (out/'report.json').write_text(json.dumps(dict(schema_version=1,playable=False,cases=results),indent=2)+'\n')
if __name__=='__main__':main()

#!/usr/bin/env python3
"""Generate explicit portable scalar traversal for the isolated OpenTitus kernel.
Pointers are handled separately as checked resource/slot indices. No memory dumps.
"""
from pathlib import Path
import re
root=Path(__file__).resolve().parents[1]
base=root/'engines/fox_dos/legacy/include'
clean=lambda s: re.sub(r'/\*.*?\*/|//[^\n]*','',s,flags=re.S)
types={'int':('-2147483647LL-1','2147483647LL'),'unsigned int':('0','4294967295LL'),'unsigned char':('0','255'),'uint8':('0','255'),'int8':('-128','127'),'int16':('-32768','32767'),'uint16':('0','65535'),'fox_bool':('-2147483647LL-1','2147483647LL')}
fields={}
for name,body in re.findall(r'struct _TITUS_(\w+)\s*\{(.*?)\};',clean((base/'level.h').read_text()),re.S):
 fields[name]=[]
 for declaration in body.split(';'):
  declaration=declaration.strip()
  if not declaration:continue
  m=re.fullmatch(r'(unsigned int|unsigned char|int|int16|uint16|uint8|int8|fox_bool)\s+(.+)',declaration)
  if m:
   for field in m[2].split(','):
    field=field.strip()
    if '*' in field:continue
    a=re.fullmatch(r'(\w+)(?:\[(\d+)\])?',field)
    if not a:raise ValueError(field)
    for index in range(int(a[2])) if a[2] else [None]:fields[name].append((m[1],a[1]+(f'[{index}]' if index is not None else '')))
out=['/* SPDX-License-Identifier: GPL-3.0-or-later */','/* Generated by tools/generate_fox_dos_state.py; do not edit. */', '#include "kernel.h"','#include "globals.h"','#include "original.h"','#include <stdio.h>','#include <stdint.h>','#include <string.h>']
out+=['extern int fox_state_names;','extern TITUS_level*fox_dos_world(void);','static int valid;static int loading;static fox_dos_visit visit;static void*context;', 'static long long scalar(const char*name,long long v,long long lo,long long hi){long long n=visit(context,name,v);if(n<lo||n>hi){valid=0;return v;}return n;}', '#define V(field,lo,hi) do{if(fox_state_names)snprintf(key,sizeof key,"%s.%s",prefix,#field);long long n=scalar(key,p->field,lo,hi);if(loading)p->field=n;}while(0)']
for name,fs in fields.items():
 out+=['static void state_'+name+'(TITUS_'+name+'*p,const char*prefix){char key[160]={0};']
 for typ,field in fs:
  if name=='level' and field not in ['lives','extrabonus']:continue
  out+=['V('+field+','+','.join(types[typ])+');']
 out+=['}']
out+=['#undef V','int fox_dos_scalars(fox_dos_visit fn,void*ctx,int restore){valid=1;loading=restore;visit=fn;context=ctx;char key[160]={0};TITUS_level*w=fox_dos_world();']
# Global scalar declarations and arrays outside typedef blocks.
globaltext=clean((base/'globals.h').read_text());globaltext=re.sub(r'typedef struct\s*\{.*?\}\s*\w+\s*;','',globaltext,flags=re.S)
for typ,field,count in re.findall(r'^\s*(unsigned int|unsigned char|int|int16|uint16|uint8|int8|fox_bool)\s+(\w+)(?:\[(\d+)\])?\s*;',globaltext,re.M):
 if field in {'LAST_CLOCK','LOOPTIME','FPS','FPS_LAST','LAST_CLOCK_CORR','SUBTIME'}:continue # presentation clocks never used for gameplay
 for i in range(int(count)) if count else [None]:
  f=field+(f'[{i}]' if i is not None else '');out+=['{long long n=scalar("globals.'+f+'",'+f+','+','.join(types[typ])+');if(loading)'+f+'=n;}']
out+=['for(int i=0;i<256;++i){if(fox_state_names)snprintf(key,sizeof key,"globals.sprites[%d].enabled",i);long long n=scalar(key,sprites[i].enabled,0,1);if(loading)sprites[i].enabled=n;if(fox_state_names)snprintf(key,sizeof key,"globals.sprites[%d].NUM",i);n=scalar(key,sprites[i].NUM,0,65535);if(loading)sprites[i].NUM=n;if(fox_state_names)snprintf(key,sizeof key,"globals.spritedata[%d].enabled",i);n=scalar(key,spritedata[i].enabled,0,1);if(loading)spritedata[i].enabled=n;if(fox_state_names)snprintf(key,sizeof key,"globals.spritedata[%d].NUM",i);n=scalar(key,spritedata[i].NUM,0,65535);if(loading)spritedata[i].NUM=n;}']
out+=['state_level(w,"level");state_player(&w->player,"player");']
for name in ['object','enemy','bonus','gate','elevator','trash']:
 typ='sprite' if name=='trash' else name
 out+=['for(int i=0;i<w->'+name+'count;++i){if(fox_state_names)snprintf(key,sizeof key,"'+name+'[%d]",i);state_'+typ+'(&w->'+name+'[i],key);'+('if(fox_state_names)snprintf(key,sizeof key,"'+name+'[%d].sprite",i);state_sprite(&w->'+name+'[i].sprite,key);' if name in ['object','enemy','elevator'] else '')+'}']
for name in ['sprite','sprite2','sprite3']:out+=['state_sprite(&w->player.'+name+',"player.'+name+'");']
out+=['for(int i=0;i<256;++i){if(fox_state_names)snprintf(key,sizeof key,"tile[%d]",i);state_tile(&w->tile[i],key);}', 'for(int y=0;y<w->height;++y)for(int x=0;x<w->width;++x){if(fox_state_names)snprintf(key,sizeof key,"map[%d][%d]",y,x);long long n=scalar(key,w->tilemap[y][x],0,255);if(loading)w->tilemap[y][x]=n;}', 'return valid;}']
(root/'engines/fox_dos/state_scalars.c').write_text('\n'.join(out)+'\n')
